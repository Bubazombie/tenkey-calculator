import { expect, test } from "vitest";
import { formatForDisplay } from "./displayNumber";

test.each([
  ["0", "0"],
  ["1024", "1024"],
  ["-2.5", "-2.5"],
  ["9999999999", "9999999999"],
  ["-999999999", "-999999999"],
  ["0.3333333333333333333333333333333333", "0.333333333"],
  ["0.6666666666666666666666666666666667", "0.666666667"],
  ["-0.6666666666666666666666666666666667", "-0.66666667"],
  ["1234567.891234", "1234567.891"],
  ["12345.6", "12345.6"],
  // Ties round half away from zero, on both signs.
  ["0.0000000005", "0.000000001"],
  ["-0.000000005", "-0.00000001"],
  ["0.00000000049", "0"],
  ["2.0000000005", "2.000000001"],
  ["-2.000000005", "-2.00000001"],
  ["-2.0000000045", "-2"],
  // Carries into the whole part.
  ["0.99999999999", "1"],
  ["-0.9999999999", "-1"],
  ["99.999999999", "100"],
  // Leftovers of inexact results disappear, and never as -0.
  ["0.9999999999999999999999999999999999", "1"],
  ["-0.0000000000000000000000000000000001", "0"],
  ["1.9999999999999999999999999999999999", "2"],
  ["0.0000000001", "0"],
  ["0.00010000000001", "0.0001"],
])("%s shows as %s", (value, expected) => {
  expect(formatForDisplay(value)).toEqual({ kind: "number", text: expected });
});

test.each([
  "10000000000",
  "9999999999.6",
  "-1000000000",
  "-999999999.5",
  "1000000000000000000000000000000000",
])("%s is too large to display", (value) => {
  expect(formatForDisplay(value)).toEqual({ kind: "tooLarge" });
});
